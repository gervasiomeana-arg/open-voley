export const translateUi = (text: string, locale: AppLocale): string =>
  locale === 'pt-BR' ? (ptBR[text] ?? text) : text;

const translatedAttributes = ['title', 'aria-label', 'placeholder', 'alt'] as const;

export const LocalizedTree: React.FC<React.PropsWithChildren<{ locale: AppLocale }>> = ({ locale, children }) => {
  const translateNode = (node: React.ReactNode): React.ReactNode => {
    if (typeof node === 'string') {
      const match = node.match(/^(\s*)([\s\S]*?)(\s*)$/);
      if (!match) return node;
      const normalized = match[2].replace(/\s+/g, ' ').trim();
      return `${match[1]}${translateUi(normalized, locale)}${match[3]}`;
    }
    if (Array.isArray(node)) return node.map(translateNode);
    if (!React.isValidElement(node)) return node;

    const props = node.props as Record<string, unknown>;
    const nextProps: Record<string, unknown> = {};
    for (const attribute of translatedAttributes) {
      const value = props[attribute];
      if (typeof value === 'string') nextProps[attribute] = translateUi(value, locale);
    }
    if ('children' in props) nextProps.children = translateNode(props.children as React.ReactNode);
    return React.cloneElement(node, nextProps);
  };

  return React.createElement(React.Fragment, null, translateNode(children));
};

export const getStoredLocale = (): AppLocale => {
  if (typeof window === 'undefined') return 'es';
  return window.localStorage.getItem('openvoley_public_locale') === 'pt-BR' ? 'pt-BR' : 'es';
};
