import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import express from 'express';
import { once } from 'node:events';
import { execFileSync } from 'node:child_process';
import { launchConfiguration, productionConfigurationErrors, readClientBuild, MANUAL_LAUNCH_CHECKS, validPublicUrl } from './launchReadiness';
const original = process.cwd(), root = fs.mkdtempSync(path.join(os.tmpdir(), 'ov-readiness-'));
process.chdir(root);
const env = { NODE_ENV: 'production', SESSION_SECRET: 'test-private-secret-longer-than-32-characters', GOOGLE_CLIENT_ID: 'test-google-client', ADMIN_EMAILS: 'admin@example.test', APP_URL: 'https://test.invalid', MERCADOPAGO_ACCESS_TOKEN: 'private-mp-token', MERCADOPAGO_WEBHOOK_SECRET: 'private-signature', GEMINI_API_KEY: 'private-ai-key', ALLOW_IFRAME_PREVIEW: 'false' };
Object.assign(process.env, env);
process.env.OPENVOLEY_DB_PATH = path.join(root, 'test.db');
const build = { version: 1 as const, builtAt: '2026-10-11T04:00:00Z', googleClientId: 'test-google-client' };
assert.equal(productionConfigurationErrors(env).length, 0);
assert.ok(productionConfigurationErrors({ ...env, SESSION_SECRET: 'short' }).length);
assert.ok(productionConfigurationErrors({ ...env, ADMIN_EMAILS: 'admin' }).length);
for (const url of ['https://', 'http://test.invalid', 'https://user:pass@test.invalid', 'https://test.invalid/?secret=x', 'https://test.invalid/#fragment'])
    assert.equal(validPublicUrl(url), false);
assert.equal(launchConfiguration(env, build, { healthy: true, activeDriver: 'sqlite', fallbackActive: false }).checks.every(c => c.ok), true);
assert.equal(launchConfiguration(env, { ...build, googleClientId: 'different' }).checks.find(c => c.id === 'client-google')?.ok, false);
assert.equal(launchConfiguration(env, null).checks.find(c => c.id === 'client-google')?.ok, false);
assert.equal(launchConfiguration({ ...env, ALLOW_IFRAME_PREVIEW: 'true' }, build).checks.find(c => c.id === 'frame')?.ok, false);
assert.equal(launchConfiguration(env, build, { healthy: true, activeDriver: 'json', fallbackActive: true }).checks.find(c => c.id === 'sqlite')?.ok, false);
assert.equal(readClientBuild(), null);
fs.mkdirSync('server-build');
fs.writeFileSync('server-build/client-build.json', JSON.stringify(build));
assert.deepEqual(readClientBuild(), build);
const { loadAccounts, saveAccounts } = await import('./accountStore');
const { createSessionToken } = await import('./sessionSecurity');
const { commercialRouter } = await import('./commercialRouter');
const { securityMiddleware } = await import('./securityMiddleware');
const { getLaunchReview } = await import('./commercialStore');
await saveAccounts([{ id: 'admin', email: env.ADMIN_EMAILS, name: 'Admin', firstLoginDate: new Date().toISOString(), trialDurationDays: 7 }, { id: 'user', email: 'user@example.test', firstLoginDate: new Date().toISOString(), trialDurationDays: 7 }]);
const admin = await createSessionToken({ userId: 'admin', email: env.ADMIN_EMAILS }), user = await createSessionToken({ userId: 'user', email: 'user@example.test' });
const app = express();
app.use(express.json(), securityMiddleware, commercialRouter);
const server = app.listen(0, '127.0.0.1');
await once(server, 'listening');
const base = `http://127.0.0.1:${(server.address() as any).port}`;
const call = (token = '', method = 'GET', body?: any) => fetch(base + '/api/commercial/readiness', { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
try {
    assert.equal((await call()).status, 401);
    assert.equal((await call(user)).status, 403);
    assert.equal((await call(user, 'PUT', { checks: {} })).status, 403);
    const result = await call(admin);
    assert.equal(result.status, 200);
    const data = await result.json();
    const serialized = JSON.stringify(data);
    for (const secret of [env.SESSION_SECRET, env.MERCADOPAGO_ACCESS_TOKEN, env.MERCADOPAGO_WEBHOOK_SECRET, env.GEMINI_API_KEY, env.GOOGLE_CLIENT_ID])
        assert.equal(serialized.includes(secret), false);
    assert.equal(data.review, null);
    assert.ok(result.headers.get('content-security-policy')?.includes('frame-ancestors'));
    assert.equal(result.headers.get('strict-transport-security'), 'max-age=31536000; includeSubDomains');
    assert.equal((await call(admin, 'PUT', { checks: {} })).status, 400);
    const checks = Object.fromEntries(Object.keys(MANUAL_LAUNCH_CHECKS).map(id => [id, false]));
    checks.isolation = true;
    assert.equal((await call(admin, 'PUT', { checks, notes: 'x'.repeat(1001) })).status, 400);
    assert.equal((await call(admin, 'PUT', { checks: { ...checks, isolation: 'yes' } })).status, 400);
    const saved = await call(admin, 'PUT', { checks, notes: 'Dos cuentas de prueba verificadas.' });
    assert.equal(saved.status, 200);
    const review = (await saved.json()).review;
    assert.equal(review.admin, env.ADMIN_EMAILS);
    assert.equal(review.builtAt, build.builtAt);
    assert.equal((await getLaunchReview()).checks.restore, false);
    assert.equal((await loadAccounts()).length, 2);
    assert.deepEqual((await (await call(admin)).json()).review, review);
    fs.writeFileSync('server-build/client-build.json', JSON.stringify({ ...build, builtAt: '2026-10-12T04:00:00Z' }));
    const changed = await (await call(admin)).json();
    assert.notEqual(changed.builtAt, changed.review.builtAt);
    const cli = execFileSync(process.execPath, ['--import', import.meta.resolve('tsx'), new URL('../../scripts/checkLaunch.ts', import.meta.url).pathname], { cwd: root, env: process.env, encoding: 'utf8' });
    assert.ok(cli.includes('Esta comprobación no valida'));
    assert.equal(cli.includes(env.MERCADOPAGO_ACCESS_TOKEN), false);
    console.log('Launch readiness tests passed: Google build mismatch, secret redaction, admin permissions, strict preview flag, review validation and new-build detection.');
}
finally {
    await new Promise<void>((resolve, reject) => server.close(e => e ? reject(e) : resolve()));
    process.chdir(original);
    fs.rmSync(root, { recursive: true, force: true });
}
